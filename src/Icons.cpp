QPainterPath parsePath(const QString& d)
{
    static const QRegularExpression re(R"(([A-Za-z])|([-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?))");
    QStringList tok;
    for (auto it = re.globalMatch(d); it.hasNext();) tok << it.next().captured(0);

    QPainterPath path;
    path.setFillRule(Qt::WindingFill);
    QPointF cur, start, lastCtrl;
    QChar cmd, prev;
    int i = 0;
    auto num = [&] { return tok.value(i++).toDouble(); };
    while (i < tok.size()) {
        if (tok[i][0].isLetter()) cmd = tok[i++][0];
        const bool rel = cmd.isLower();
        const QChar up = cmd.toUpper();
        const QPointF o = rel ? cur : QPointF(0, 0);
        auto pt = [&] { const double x = num(); const double y = num(); return QPointF(x, y) + o; };
        if (up == 'M') {
            cur = start = pt();
            path.moveTo(cur);
            cmd = rel ? QChar('l') : QChar('L');
        } else if (up == 'L') {
            cur = pt();
            path.lineTo(cur);
        } else if (up == 'H') {
            cur.setX(num() + (rel ? cur.x() : 0));
            path.lineTo(cur);
        } else if (up == 'V') {
            cur.setY(num() + (rel ? cur.y() : 0));
            path.lineTo(cur);
        } else if (up == 'C') {
            const QPointF c1 = pt(); const QPointF c2 = pt(); const QPointF e = pt();
            path.cubicTo(c1, c2, e);
            lastCtrl = c2; cur = e;
        } else if (up == 'S') {
            const bool wasCurve = prev.toUpper() == 'C' || prev.toUpper() == 'S';
            const QPointF c1 = wasCurve ? cur * 2 - lastCtrl : cur;
            const QPointF c2 = pt(); const QPointF e = pt();
            path.cubicTo(c1, c2, e);
            lastCtrl = c2; cur = e;
        } else if (up == 'Z') {
            path.closeSubpath();
            cur = start;
        } else {
            break;   // unsupported command
        }
        prev = cmd;
    }
    return path;
}
