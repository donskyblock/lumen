QImage IconProvider::requestImage(const QString& id, QSize* size, const QSize&)
{
    const QStringList p = id.split('@');
    if (p.size() < 3) return {};
    const int px = qBound(8, p[1].toInt(), 512);
    QColor color(QStringLiteral("#") + p[2]);
    if (!color.isValid()) color = Qt::white;
    const QString data = iconData().value(p[0]);
    if (data.isEmpty()) return {};

    static thread_local QHash<QString, QPainterPath> cache;
    auto it = cache.find(p[0]);
    if (it == cache.end()) it = cache.insert(p[0], parsePath(data));

    QImage img(px, px, QImage::Format_ARGB32_Premultiplied);
    img.fill(Qt::transparent);
    QPainter g(&img);
    g.setRenderHint(QPainter::Antialiasing);
    g.scale(px / 24.0, px / 24.0);
    g.fillPath(*it, color);
    if (size) *size = img.size();
    return img;
}
